"""Rebuild the assignment's four result tables from preserved raw evidence."""

from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path
from statistics import mean

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "experiments/raw"


def _read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def _percentile(values: list[float], q: float) -> str:
    if not values:
        return "not measured"
    return f"{np.quantile(values, q, method='linear'):.1f}"


def _mean_tokens(rows: list[dict]) -> str:
    totals = [int(row["tokens_in"]) + int(row["tokens_out"]) for row in rows
              if row.get("tokens_in") not in (None, "") and row.get("tokens_out") not in (None, "")]
    return f"{mean(totals):.1f}" if totals else "not measured"


def _pct(numerator: int, denominator: int) -> str:
    return f"{100 * numerator / denominator:.1f}" if denominator else "not measured"


def _md_row(items: list[object]) -> str:
    return "| " + " | ".join(str(item).replace("|", "\\|").replace("\n", " ") for item in items) + " |"


def build() -> str:
    with (RAW / "results.csv").open(newline="", encoding="utf-8") as stream:
        results = list(csv.DictReader(stream))
    runs = [run for run in _read_jsonl(RAW / "load_runs.jsonl") if run.get("valid")]
    run_ids = {run["scenario"]: {req["request_id"] for req in run.get("requests", []) if req.get("request_id")}
               for run in runs}
    by_id = {row["request_id"]: row for row in results}
    scenario_doc = yaml.safe_load((ROOT / "config/scenarios.yaml").read_text(encoding="utf-8"))
    configured_names = set(scenario_doc["scenarios"])
    if configured_names != {run["scenario"] for run in runs}:
        raise ValueError("Valid run scenarios do not match the five fixed scenario configurations")
    valid_scenarios = {run["scenario"]: run for run in runs}
    provider = json.loads((RAW / "provider_limit_evidence.json").read_text(encoding="utf-8"))
    account_limits = provider["account_specific_values"]
    documented = provider["documented_current_free_plan_reference"]
    headers = [item.get("headers", {}) for item in provider["account_header_evidence"]["headers_by_request"]]
    observed_tpm = {int(item["x-ratelimit-limit-tokens"]) for item in headers if item.get("x-ratelimit-limit-tokens")}
    observed_rpd = {int(item["x-ratelimit-limit-requests"]) for item in headers if item.get("x-ratelimit-limit-requests")}
    events = provider.get("observed_rate_limit_events", [])
    limit_event = events[0] if events else None
    rpm_account = account_limits.get("requests_per_minute")
    tpm_value = next(iter(observed_tpm)) if len(observed_tpm) == 1 else "Not measured"
    rpd_value = next(iter(observed_rpd)) if len(observed_rpd) == 1 else "Not measured"
    tpd_account = account_limits.get("tokens_per_day")
    rpm_value = (f"{rpm_account}/min confirmed" if rpm_account is not None else
                 f"Not confirmed for this account; published reference {documented['requests_per_minute']}/min")
    tpd_value = (f"{tpd_account}/day confirmed" if tpd_account is not None else
                 f"Not confirmed for this account; published reference {documented['tokens_per_day']:,}/day")

    lines = [
        "# Reproducible result tables",
        "",
        "Generated by `python scripts/build_final_tables.py` from `experiments/raw/` and the frozen configuration. Percentages and times are formatted to one decimal; percentiles use NumPy's linear quantile method.",
        "",
        "## Table 1. Limits observed for the real Groq service",
        "",
        _md_row(["Limit", "Value", "How found", "Confidence"]),
        _md_row(["---", "---", "---", "---"]),
        _md_row(["Requests/minute (RPM)", rpm_value, f"Official high-level model table ({provider['documentation_checked_at']}); account Limits page not accessed", "Low for account value"]),
        _md_row(["Tokens/minute (TPM)", f"{tpm_value:,} observed" if isinstance(tpm_value, int) else tpm_value, "Successful response headers; separate provider limit event is preserved in the evidence JSON", "High for observed header / event"]),
        _md_row(["Requests/day (RPD)", f"{rpd_value:,} observed" if isinstance(rpd_value, int) else rpd_value, "Successful response headers; official header names this RPD", "High for observed header"]),
        _md_row(["Tokens/day (TPD)", tpd_value, f"Official high-level model table ({provider['documentation_checked_at']}); account Limits page not accessed", "Low for account value"]),
        _md_row(["Requests in flight", account_limits.get("requests_in_flight") or "Not measured", "No concurrent real-provider experiment was run", "Not measured"]),
        _md_row(["On limit", f"HTTP 429; {limit_event['response'] if limit_event else 'no limit event captured'}", f"Real {limit_event['dimension'] if limit_event else 'provider'} response; raw evidence retains request ID and error" if limit_event else "No real limit response recorded", "High for this event" if limit_event else "Not measured"]),
        _md_row(["Recovery time", account_limits.get("recovery_time", "Not measured"), "Later success followed a longer cooldown; the exact boundary was not measured", "Not measured"]),
        "",
        "## Table 2a. Latency and offered load by stand-in scenario",
        "",
        _md_row(["Scenario", "Source", "Requests sent", "Duration (s)", "Offered/min", "First response p50/p95/p99 (ms)", "Total p50/p95/p99 (ms)"]),
        _md_row(["---", "---", "---:", "---:", "---:", "---", "---"]),
    ]
    ordered_scenarios = ["steady", "burst", "sustained_overload", "per_minute_limit_halved", "daily_budget_exhausted"]
    scenario_rows: dict[str, list[dict]] = {}
    for name in ordered_scenarios:
        run = valid_scenarios[name]
        rows = [by_id[rid] for rid in run_ids[name] if rid in by_id]
        scenario_rows[name] = rows
        duration = float(run.get("offered_elapsed_seconds") or 0)
        rate = len(rows) / duration * 60 if duration else None
        success = [row for row in rows if row["status"] == "ok"]
        first = [float(row["first_token_ms"]) for row in success if row.get("first_token_ms")]
        total = [float(row["total_ms"]) for row in success if row.get("total_ms")]
        lines.append(_md_row([
            name, "stand-in", len(rows), f"{duration:.1f}", f"{rate:.1f}" if rate is not None else "not measured",
            "/".join(_percentile(first, q) for q in (.50, .95, .99)),
            "/".join(_percentile(total, q) for q in (.50, .95, .99)),
        ]))

    lines += [
        "",
        "## Table 2b. Outcomes by the same stand-in scenario",
        "",
        _md_row(["Scenario", "Succeeded %", "Rate-limited %", "Timed out / given up %", "Retries/request", "Peak queue", "Tokens/successful answer", "Cost/1,000 answers"]),
        _md_row(["---", "---:", "---:", "---:", "---:", "---:", "---:", "---"]),
    ]
    for name in ordered_scenarios:
        rows = scenario_rows[name]
        n = len(rows)
        ok = sum(row["status"] == "ok" for row in rows)
        limited = sum(row["status"] == "rate_limited" for row in rows)
        given_up = sum(row["status"] in {"timeout", "error"} for row in rows)
        retries = sum(int(row.get("retries") or 0) for row in rows)
        queue_peak = max((int(row.get("peak_queue_length") or 0) for row in rows), default=0)
        success_rows = [row for row in rows if row["status"] == "ok"]
        lines.append(_md_row([
            name, _pct(ok, n), _pct(limited, n), _pct(given_up, n),
            f"{retries / n:.2f}" if n else "not measured", queue_peak, _mean_tokens(success_rows), "not measured",
        ]))

    answers = _read_jsonl(RAW / "evaluation_answers.jsonl")
    retrieval_cfg = yaml.safe_load((ROOT / "config/retrieval.yaml").read_text(encoding="utf-8"))
    lines += [
        "",
        "## Table 3. Retrieval settings",
        "",
        _md_row(["Setting (chunk size; overlap; top-k; rerank)", "Asked (graded)", "Correct + cited %", "Wrong %", "Correctly refused %", "Tokens/successful answer", "First response p50/p95 (ms)", "Total p50/p95 (ms)"]),
        _md_row(["---", "---:", "---:", "---:", "---:", "---:", "---", "---"]),
    ]
    settings = retrieval_cfg["settings"]
    for setting in ["small_fast", "medium", "medium_reranked"]:
        spec = settings[setting]
        if setting == "medium_reranked":
            spec_label = f"{setting} ({spec['chunk_size_chars']}; {spec['chunk_overlap_chars']}; {spec['top_k']}; BM25 {spec['candidate_k']} to {spec['top_k']})"
        else:
            spec_label = f"{setting} ({spec['chunk_size_chars']}; {spec['chunk_overlap_chars']}; {spec['top_k']}; no)"
        rows = [row for row in answers if row["retrieval_setting"] == setting]
        successful = [row for row in rows if row["status"] == "ok"]
        graded = [row for row in successful if row.get("answer_grade")]
        grades = Counter(row["answer_grade"] for row in graded)
        request_rows = [by_id[row["request_id"]] for row in successful if row["request_id"] in by_id]
        first = [float(row["first_token_ms"]) for row in request_rows if row.get("first_token_ms")]
        total = [float(row["total_ms"]) for row in request_rows if row.get("total_ms")]
        asked_text = f"{len(rows)} ({len(graded)} graded)"
        lines.append(_md_row([
            spec_label, asked_text,
            _pct(grades["correct"], len(graded)),
            _pct(grades["wrong"] + grades["refused_wrongly"], len(graded)),
            _pct(grades["refused_correctly"], len(graded)),
            _mean_tokens(request_rows),
            f"{_percentile(first, .50)}/{_percentile(first, .95)}",
            f"{_percentile(total, .50)}/{_percentile(total, .95)}",
        ]))

    lines += [
        "",
        "## Metric definitions and limitations",
        "",
        "- Tables 2a/2b include only each scenario's valid measured end-user offers; invalid harness attempts remain in `load_runs.jsonl` and are excluded. The daily-budget row includes one measured application probe after five simulator bootstrap calls; those setup calls are not end-user requests.",
        "- Table 2a latency percentiles use `status=ok` only (n shown implicitly by the success counts in Table 2b); `first_token_ms` is the first user-visible response time because the graph buffers answers until verification. Model-first-token timing is retained separately in traces.",
        "- Table 2b success, rate-limit, and given-up percentages use all offered end-user requests. Given-up means terminal `timeout` or `error` status. Tokens per answer are mean input+output counts over successful answers; stand-in counts are synthetic.",
        "- Cost per 1,000 answers is not measured: no billing record or dated price basis was captured. Free-tier use is not converted into a hypothetical list-price bill.",
        "- Table 3 covers all 15 distinct answerable questions under each setting. Three questions were repeated once per setting by a resume-filter source-label mismatch, so 18 request rows appear per setting. Grade percentages use only successful, manually graded outputs; operational failures remain visible in `phase4_answer_metrics.json` and are excluded from the grade denominator. `wrong` includes `refused_wrongly`.",
        "- Real provider account-specific RPM, TPD, concurrent requests, and exact recovery time were not confirmed. The published model table is a high-level reference only; the account Limits page is authoritative.",
        "",
        "### Supporting evidence",
        "",
        "- Raw request rows: `experiments/raw/results.csv`; traces: `experiments/raw/request_traces.jsonl`.",
        "- Run validity/offered rates: `experiments/raw/load_runs.jsonl`; scenarios: `config/scenarios.yaml`.",
        "- Real provider evidence: `experiments/raw/provider_limit_evidence.json`.",
        "- Evaluation grades and question references: `experiments/raw/evaluation_grades.yaml` and `src/relay/evaluation/questions.yaml`.",
        "- Official Groq rate-limit documentation (reviewed 2026-11-10): https://console.groq.com/docs/rate-limits.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    output = ROOT / "submissions/final_tables.md"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build(), encoding="utf-8")
    print(f"Wrote {output.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
